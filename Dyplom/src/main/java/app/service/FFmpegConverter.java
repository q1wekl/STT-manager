package app.service;

import java.io.File;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

public class FFmpegConverter {
    private final String ffmpegPath = "bin/ffmpeg.exe";

    public List<File> convertAndSplitToWav(File input){
        File tempDir = new File("temp/chunks_"+  System.currentTimeMillis());
        tempDir.mkdirs();

        File outputPattern = new File(tempDir, "chunk_%03d.wav");
        try{
            ProcessBuilder pb = new ProcessBuilder(
                    ffmpegPath,
                    "-y",
                    "-i", input.getAbsolutePath(),
                    "-ar", "16000",
                    "-ac", "1",
                    "-f", "wav",
                    outputPattern.getAbsolutePath()
            );
            Process process=pb.start();
            int code= process.waitFor();
            if(code!=0){
                throw new RuntimeException("FFmpeg failed: " + code);
            }

            File[] files= tempDir.listFiles((dir,name)->name.endsWith(".wav"));
            if(files ==null|| files.length==0){
                throw new RuntimeException("No chunks generated by FFmpeg");
            }
            Arrays.sort(files);
            return new ArrayList<>(Arrays.asList(files));

        }catch (Exception e){
            throw new RuntimeException("FFmpeg error: ", e);
        }
    }

    public File convertToWav(File input){
        File output = new File("temp/audio_" + System.currentTimeMillis() + ".wav");
        output.getParentFile().mkdirs();

        try{
            ProcessBuilder pb = new ProcessBuilder(
                    ffmpegPath,
                    "-y",
                    "-i", input.getAbsolutePath(),
                    "-ar", "16000",
                    "-ac", "1",
                    "-f", "wav",
                    output.getAbsolutePath()
            );

            Process process= pb.start();
            int code = process.waitFor();
            if(code!=0){
                throw new RuntimeException("FFmpeg failed: "+ code);
            }
            return output;

        }catch(Exception e){
            throw new RuntimeException("FFmpeg error: ",e);
        }
    }
}
